const { chromium } = require('D:/PM.funion/.playwright/package/index.js');
const assert = require('node:assert/strict');
const OUT = 'D:/PM.funion/screenshots';
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 1600, height: 950 } });
  const page = await context.newPage();
  page.setDefaultTimeout(15000);
  const errors = [];
  let passed = 0;
  const ok = name => { passed++; console.log('PASS', name); };
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') console.log('CONSOLE', m.text()); });
  const home = page.locator('section.show .vs-home');
  const go = async () => {
    await page.goto('http://localhost:5173/', { waitUntil: 'commit', timeout: 60000 });
    await page.waitForFunction(() => document.querySelectorAll('.nav-parent').length > 0, null, { timeout: 60000 });
    await page.locator('.ops-center .nav-parent').filter({ hasText: '系列编码知识库' }).click();
    await page.locator('.ops-center .subnav').filter({ hasText: '素材中心' }).click();
    await home.waitFor();
  };
  const shot = async name => {
    await page.waitForFunction(() => !document.querySelector('.toast-wrap .toast'));
    await page.screenshot({ path: `${OUT}/${name}.png` });
  };
  const viewTab = name => home.locator('.vs-view').filter({ hasText: new RegExp(`^${name}$`) }).click();
  try {
    await go();
    const bgImg = await home.evaluate(el => getComputedStyle(el).backgroundImage);
    assert.match(bgImg, /linear-gradient/);
    assert.equal(await home.locator('.vs-view').count(), 3);
    assert.equal(await home.locator('.vs-mode').count(), 2);
    assert.equal(await home.locator('.vs-spark').count(), 4);
    ok('白底渐变首页、创作/资产/历史创作三视图、顶部动效装饰');

    await viewTab('历史创作');
    assert.equal(await home.locator('.vs-card').count(), 0);
    assert.equal(await home.locator('.vs-pill').count(), 0);
    assert.match(await home.locator('.vs-empty-t').innerText(), /暂无历史创作/);
    await shot('video-home-history-empty');
    await viewTab('创作');
    assert.equal(await home.locator('.vs-card').count(), 1);
    assert.equal(await home.locator('.vs-recent').count(), 0);
    ok('空历史仅展示空状态、隐藏输入卡');

    await home.locator('.vs-pref').click();
    assert.equal(await home.locator('.vs-ratio-cell').count(), 7);
    await home.locator('.vs-ratio-cell').filter({ hasText: '3:4' }).click();
    assert.equal(await home.locator('.vs-ratio-cell.on').innerText(), '3:4');
    assert.equal(await home.locator('.pref-pop .vs-sel').count(), 2);
    await home.locator('.pref-pop .vs-sel').first().locator('.bselect-trigger').click();
    await page.locator('.bselect-menu:visible .bselect-opt').first().click();
    await home.locator('.vs-hero-t').click();
    assert.equal(await home.locator('.pref-pop').count(), 0);
    ok('生成偏好气泡：比例七档＋时长/帧率下拉、点外关闭');

    await home.locator('.vs-tile.add').click();
    const menu = home.locator('.add-pop .vs-pop-item');
    assert.deepEqual(await menu.allInnerTexts(), ['上传图片', '选择商品']);
    await menu.filter({ hasText: '选择商品' }).click();
    await home.locator('.vs-pick-search').fill('精华');
    await home.locator('.vs-pick-row').first().click();
    assert.equal(await home.locator('.vs-stack').count(), 1);
    assert.equal((await home.locator('.vs-stack-n').innerText()).trim(), '6');
    await home.locator('.vs-stack').click();
    assert.equal(await home.locator('.vs-tilewrap.prod .vs-tile-tag').count(), 6);
    assert.equal(await home.locator('.vs-tilewrap.prod > :last-child').getAttribute('class'), 'vs-fold');
    await shot('video-home-create-expanded');
    await home.locator('.vs-tilewrap.prod .vs-tile.img').first().click();
    await page.locator('.vs-pvstage img').waitFor();
    assert.equal(await page.locator('.vs-pvthumb').count(), 6);
    await page.locator('.vs-pvthumb').nth(2).click();
    assert.ok(await page.locator('.vs-pvthumb').nth(2).evaluate((el) => el.classList.contains('on')));
    await page.locator('.vs-pvclose').click();
    await home.locator('.vs-tilewrap.prod .vs-tile-x').first().click();
    assert.equal(await home.locator('.vs-tilewrap.prod .vs-tile-tag').count(), 5);
    await home.locator('.vs-fold').click();
    assert.equal((await home.locator('.vs-stack-n').innerText()).trim(), '5');
    await home.getByPlaceholder('描述想要的视频效果，例如：突出卖点、节奏轻快').fill('门店演示视频');
    await page.setInputFiles('section.show .vs-home input[accept="image/*"]', 'D:/PM.funion/screenshots/video-studio-1280.png');
    assert.equal(await home.locator('.vs-tile.img').count(), 1);
    await shot('video-home-create-1600');
    ok('商品多图：收起叠堆计数、展开全量、黑底预览缩略条切换、单张删除');

    await home.locator('.vs-go').click();
    assert.equal(await home.locator('.vs-go .vs-spin').count(), 1);
    await page.locator('.toast-wrap .toast').filter({ hasText: '演示生成完成' }).waitFor({ timeout: 10000 });
    assert.equal(await home.locator('.vs-recent-card').count(), 1);
    assert.match(await home.locator('.vs-recent-name').first().innerText(), /.+/);
    assert.match(await home.locator('.vs-recent-sub').first().innerText(), /生成｜5秒｜3:4/);
    await shot('video-home-recent');
    await home.locator('.vs-recent-card').first().click();
    assert.equal(await home.locator('.vs-view.on').innerText(), '历史创作');
    assert.equal(await home.locator('.vs-rec').count(), 1);
    await viewTab('历史创作');
    assert.equal(await home.locator('.vs-rec').count(), 1);
    const meta = (await home.locator('.vs-rec-meta').innerText()).replace(/\s*\n\s*/g, ' | ');
    assert.match(meta, /生成 \| .+ \| 5秒 \| 3:4 \| 30fps/);
    assert.match(await home.locator('.vs-rec-status').innerText(), /演示生成完成/);
    assert.equal(await home.locator('.vs-fan-card').count(), 6);
    assert.equal(await home.locator('.vs-player').count(), 1);
    await home.locator('.vs-player .vs-pp').click();
    await page.waitForTimeout(600);
    assert.match(await home.locator('.vs-time').innerText(), /00:0\d \/ 00:05/);
    await home.locator('.vs-player .vs-pp').click();
    await shot('video-home-history');
    await home.locator('.vs-fan-more').click();
    assert.equal(await home.locator('.vs-rec-fan.open').count(), 1);
    await shot('video-home-fan-hover');
    await home.locator('.vs-fan-card').first().click();
    await page.locator('.vs-pvstage').waitFor();
    assert.ok((await page.locator('.vs-pvthumb').count()) >= 1);
    await page.locator('.vs-pvclose').click();
    await home.locator('.vs-fan-more').click();
    assert.equal(await home.locator('.vs-rec-fan.open').count(), 0);
    await home.locator('.vs-rec-head').hover();
    await page.waitForTimeout(300);
    const pb = await home.locator('.vs-rec-prompt').evaluate((el) => getComputedStyle(el).backgroundColor);
    assert.notEqual(pb, 'rgba(0, 0, 0, 0)');
    await shot('video-home-prompt-hover');
    ok('演示生成闭环：扇堆hover散开+chevron预览、描述hover面板、播放器');

    await viewTab('资产');
    assert.equal(await home.locator('.vs-asset').count(), 1);
    await home.locator('.vs-seg.small .vs-seg-btn').filter({ hasText: '视频' }).click();
    assert.match(await home.locator('.vs-empty').innerText(), /暂无视频资产/);
    await home.locator('.vs-seg.small .vs-seg-btn').filter({ hasText: '图片' }).click();
    await home.locator('.vs-asset').first().click();
    await page.locator('.vs-pvstage img').waitFor();
    await page.locator('.vs-pvclose').click();
    await shot('video-home-assets');
    ok('资产视图：图片卡、视频空态、全屏预览');

    await viewTab('历史创作');
    assert.equal(await home.locator('.vs-pill').count(), 1);
    assert.equal(await home.locator('.vs-card.docked').count(), 0);
    await home.locator('.vs-pill').click();
    assert.equal(await home.locator('.vs-card.docked').count(), 1);
    await home.locator('.vs-act').filter({ hasText: '重新编辑' }).click();
    assert.equal(await home.locator('.vs-view.on').innerText(), '历史创作');
    assert.equal(await home.locator('.vs-prompt').inputValue(), '门店演示视频');
    assert.equal(await home.locator('.vs-stack').count(), 1);
    assert.equal(await home.locator('.vs-tile.img').count(), 1);
    ok('重新编辑就地回填停靠输入卡');

    await home.locator('.vs-act').filter({ hasText: '再次生成' }).click();
    await page.locator('.toast-wrap .toast').filter({ hasText: '演示生成完成' }).waitFor({ timeout: 10000 });
    assert.equal(await home.locator('.vs-rec').count(), 2);
    assert.equal(await home.locator('.vs-pill').count(), 1);
    await home.locator('.vs-pill').click();
    assert.equal(await home.locator('.vs-card.docked').count(), 1);
    await page.mouse.move(800, 500);
    await page.mouse.wheel(0, 120);
    await page.waitForTimeout(250);
    const dockBox = await home.locator('.vs-card.docked').boundingBox();
    assert.ok(Math.abs(dockBox.y + dockBox.height - 938) < 4, `docked bottom ${dockBox.y + dockBox.height}`);
    assert.ok(await home.locator('.vs-totop').isVisible());
    await home.locator('.vs-totop').click();
    await page.waitForTimeout(500);
    const topScroll = await page.evaluate(() => document.querySelector('.app-content').scrollTop);
    assert.ok(topScroll < 40, `scrollTop ${topScroll}`);
    await home.locator('.vs-act.icon').first().click();
    assert.deepEqual(await home.locator('.more-pop .vs-pop-item').allInnerTexts(), ['反馈生成问题', '删除']);
    await home.locator('.more-pop .vs-pop-item.danger').click();
    assert.ok(await page.locator('.pm-host .mask').isVisible());
    await shot('video-home-del-modal');
    await page.locator('.modal-foot').getByRole('button', { name: '删除', exact: true }).click();
    assert.equal(await home.locator('.vs-rec').count(), 1);
    ok('再次生成与删除二次确认');

    await viewTab('创作');
    await home.locator('.vs-mode').filter({ hasText: '复刻' }).click();
    await home.locator('.vs-go').click();
    await page.locator('.toast-wrap .toast').filter({ hasText: '请先上传参考视频' }).waitFor();
    ok('复刻校验');

    await home.locator('.vs-mode').filter({ hasText: '生成' }).click();
    await page.setViewportSize({ width: 1280, height: 600 });
    await shot('video-home-create-1280');
    await page.setViewportSize({ width: 1600, height: 950 });
    ok('两档视口截图');

    assert.deepEqual(errors, []);
    ok('无页面脚本错误');
    console.log('ALL PASS', passed);
  } catch (e) {
    console.log('FAIL', e.message);
    await page.screenshot({ path: `${OUT}/video-home-fail.png` });
    process.exitCode = 1;
  } finally {
    await browser.close();
  }
})();
